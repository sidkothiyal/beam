CRON_TAG_PREFIX = "beam_pulse"


def _cron_tag(session_id: str) -> str:
    return f"{CRON_TAG_PREFIX}_{session_id}" if session_id else CRON_TAG_PREFIX


def install_cron(
    session_id: str,
    session_file: Path,
    interval_secs: int,
    *,
    auto_restart: bool = True,
    idle_stop: bool = False,
    auto_stop_on_complete: bool = True,
    max_retries: int = 5,
    logs_dir: Path | None = None,
) -> None:
    """Install a cron job for pulse monitoring of a session."""
    tag = _cron_tag(session_id)
    cron_expr = seconds_to_cron(interval_secs)

    beam_bin = _find_beam_bin()
    pulse_args = f"pulse check --session-file {session_file}"
    if auto_restart:
        pulse_args += " --auto-restart"
    if idle_stop:
        pulse_args += " --idle-stop"
    if auto_stop_on_complete:
        pulse_args += " --auto-stop-on-complete"
    pulse_args += f" --max-retries {max_retries}"

    log_dir = logs_dir or session_file.parent
    log_file = log_dir / "pulse_cron.log"
    log_dir.mkdir(parents=True, exist_ok=True)

    # Write a wrapper script (cron has line-length limits)
    wrapper = log_dir / f".pulse_wrapper_{session_id}.sh"
    wrapper.write_text(
        f"#!/usr/bin/env bash\n"
        f"# Generated by beam pulse install for session {session_id}\n"
        f"set -euo pipefail\n"
        f"export PATH=\"{os.environ.get('PATH', '/usr/local/bin:/usr/bin:/bin')}\"\n"
        f"export HOME=\"{Path.home()}\"\n"
        f"exec {beam_bin} {pulse_args}\n"
    )
    wrapper.chmod(0o755)

    cron_line = f"{cron_expr} {wrapper} >> {log_file} 2>&1 # {tag}"

    existing = _get_crontab()
    filtered = [l for l in existing if f"# {tag}" not in l]
    filtered.append(cron_line)
    _set_crontab(filtered)

    # Reset failure counter
    (log_dir / f".pulse_failures_{session_id}").write_text("0")

    log.done(f"Pulse cron job installed for session: {session_id}")
    log.info(f"  Schedule:  {cron_expr} (every {format_interval(interval_secs)})")
    log.info(f"  Log file:  {log_file}")
    log.info(f"  Uninstall: beam pulse uninstall --session {session_id}")


def uninstall_cron(session_id: str = "", *, logs_dir: Path | None = None) -> None:
    """Remove pulse cron job(s). If session_id is empty, remove all."""
    existing = _get_crontab()
    if session_id:
        tag = _cron_tag(session_id)
        filtered = [l for l in existing if f"# {tag}" not in l]
    else:
        filtered = [l for l in existing if f"# {CRON_TAG_PREFIX}" not in l]

    _set_crontab(filtered)

    # Cleanup state files
    if logs_dir:
        patterns = [f".pulse_*_{session_id}*"] if session_id else [".pulse_*"]
        for pat in patterns:
            for f in logs_dir.glob(pat):
                f.unlink(missing_ok=True)
        if session_id:
            session.delete_session(logs_dir, session_id)

    if session_id:
        log.done(f"Pulse cron job removed for session: {session_id}")
    else:
        log.done("All pulse cron jobs removed.")


def list_cron_sessions(logs_dir: Path) -> list[dict[str, Any]]:
    """List all sessions with their cron status."""
    sessions = session.list_sessions(logs_dir)
    crontab = "\n".join(_get_crontab())
    for s in sessions:
        tag = _cron_tag(s.get("session_id", ""))
        s["cron_active"] = f"# {tag}" in crontab
    return sessions


