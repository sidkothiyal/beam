def parse_duration(s: str) -> int:
    """Parse '5m', '1h', '30s' into seconds."""
    if not s:
        return 300
    unit = s[-1] if s[-1] in "smh" else "s"
    value = int(s.rstrip("smh"))
    return {"s": 1, "m": 60, "h": 3600}[unit] * value


def format_interval(secs: int) -> str:
    if secs >= 3600:
        return f"{secs // 3600}h {secs % 3600 // 60}m"
    if secs >= 60:
        return f"{secs // 60}m {secs % 60}s"
    return f"{secs}s"


def seconds_to_cron(secs: int) -> str:
    """Convert seconds to a cron schedule expression."""
    if secs < 60:
        return "* * * * *"
    if secs < 3600:
        mins = secs // 60
        return "* * * * *" if mins == 1 else f"*/{mins} * * * *"
    hours = secs // 3600
    return "0 * * * *" if hours == 1 else f"0 */{hours} * * *"


