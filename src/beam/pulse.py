def _find_beam_bin() -> str:
    """Find the beam CLI binary path."""
    import shutil
    found = shutil.which("beam")
    if found:
        return found
    return f"{sys.executable} -m beam.cli"


def _get_crontab() -> list[str]:
    result = subprocess.run(["crontab", "-l"], capture_output=True, text=True)
    if result.returncode != 0:
        return []
    return [l for l in result.stdout.splitlines() if l.strip()]


def _set_crontab(lines: list[str]) -> None:
    content = "\n".join(l for l in lines if l.strip())
    if not content.strip():
        subprocess.run(["crontab", "-r"], capture_output=True)
        return
    subprocess.run(["crontab", "-"], input=content + "\n", text=True, check=True)
