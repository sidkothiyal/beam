def check_provider_status(sess: dict[str, Any]) -> str:
    """Check instance status via the provider API. Returns normalised status."""
    provider = sess.get("provider", "")
    pod_id = sess.get("pod_id", "")
    if not pod_id:
        return "unknown"

    try:
        if provider == "runpod":
            from beam.providers.runpod import RunPodProvider
            p = RunPodProvider(api_key=sess.get("runpod_api_key"))
            return p.get_status(pod_id)
        elif provider in ("vast.ai", "vastai"):
            from beam.providers.vastai import VastAIProvider
            p = VastAIProvider(api_key=sess.get("vast_api_key"))
            return p.get_status(pod_id)
    except Exception:
        return "api_error"
    return "unknown"


def check_ssh_reachable(sess: dict[str, Any], cfg: BeamConfig | None = None) -> bool:
    """Check if the session's remote is reachable via SSH."""
    ip = sess.get("ip", "")
    port = sess.get("port", "22")
    if not ip:
        return False
    from beam.config import SSHConfig
    ssh_cfg = cfg.ssh if cfg else SSHConfig()
    info = SSHInfo(
        host=ip,
        port=str(port),
        user=sess.get("user", "root"),
        identity_file=sess.get("identity_file", ""),
    )
    client = SSHClient(info=info, cfg=ssh_cfg)
    try:
        return client.check()
    except Exception:
        return False


def check_gpu_usage(sess: dict[str, Any], pulse_cfg: PulseConfig | None = None) -> int:
    """Query GPU utilisation on the remote. Returns 0-100, or -1 on failure."""
    ip = sess.get("ip", "")
    port = sess.get("port", "22")
    if not ip:
        return -1

    from beam.config import SSHConfig
    info = SSHInfo(host=ip, port=str(port), user=sess.get("user", "root"),
                   identity_file=sess.get("identity_file", ""))
    client = SSHClient(info=info, cfg=SSHConfig())
    pcfg = pulse_cfg or PulseConfig()

    # Check for active compute processes first
    try:
        result = client.run(
            "nvidia-smi --query-compute-apps=pid --format=csv,noheader,nounits 2>/dev/null | grep -c '^[0-9]' || echo 0",
            check=False,
        )
        count = int(result.stdout.strip())
        if count > 0:
            return 100
    except Exception:
        return -1

    # Multi-sample peak utilisation
    sample_cmd = (
        f"for i in $(seq {pcfg.gpu_idle_samples}); do "
        f"nvidia-smi --query-gpu=utilization.gpu --format=csv,noheader,nounits 2>/dev/null; "
        f"sleep {pcfg.gpu_idle_sample_interval}; done"
    )
    try:
        result = client.run(sample_cmd, check=False)
        if not result.stdout.strip():
            return -1
        max_util = 0
        for line in result.stdout.strip().splitlines():
            val = line.strip()
            if val.isdigit():
                max_util = max(max_util, int(val))
        return max_util
    except Exception:
        return -1


